def balance_and_format_questions():
    """Ensure options are balanced across correct answer indices 0-3."""
    formatted = []
    for i, q in enumerate(raw_questions):
        idx = i + 111
        target_correct = (i % 4)
        curr_correct = q["correctIndex"]
        choices = list(q["choices"])
        correct_val = choices[curr_correct]
        
        # remove correct
        del choices[curr_correct]
        
        # insert at target_correct
        choices.insert(target_correct, correct_val)
        
        entry = {
            "id": f"greece_med_{idx:03d}",
            "text": q["question"],
            "answers": choices,
            "correctAnswerIndex": target_correct,
            "categoryId": "greece",
            "difficulty": 3,
            "explanation": q["explanation"],
            "funFacts": q["funFacts"],
            "source": q["source"],
            "locale": "el-GR",
            "tags": ["greece", "medium"],
            "status": "reviewed",
            "verifiedAt": "2026-10-25"
        }
        formatted.append(entry)
    return formatted

def check_collisions(formatted):
    existing_ids, normalized_texts, distractor_sets = load_existing_db()
    
    # Check normalized text collision
    text_collisions = 0
    for q in formatted:
        n_text = normalize_text(q["text"])
        if n_text in normalized_texts:
            print(f"COLLISION: Duplicate question text found: {q['text']}")
            text_collisions += 1
            
    # Check distractor set collision
    distractor_collisions = 0
    for q in formatted:
        distractors = "|".join(sorted([
            normalize_text(opt)
            for i, opt in enumerate(q["answers"])
            if i != q["correctAnswerIndex"]
        ]))
        if distractors in distractor_sets:
            print(f"COLLISION: Duplicate distractor set found: {distractors} in question: {q['text']}")
            distractor_collisions += 1
            
    print(f"Pre-check complete: {text_collisions} text collisions, {distractor_collisions} distractor collisions.")
    return text_collisions == 0 and distractor_collisions == 0

